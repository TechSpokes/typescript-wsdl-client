export const digest = (bytes: Uint8Array | string): string => createHash('sha256').update(bytes).digest('hex');

export async function verifyCorpus(corpus: PreparationCorpus, root: string): Promise<void> {
  for (const file of corpus.files) {
    const bytes = await readFile(path.resolve(root, file.path));
    if (bytes.length !== file.bytes || digest(bytes) !== file.sha256) throw new Error(`Corpus bytes differ: ${file.path}`);
  }
}

/** Linear declarations and use sites; every type shares Pair and recurses across an element boundary. */
export function syntheticSchema(size: number): string {
  if (!Number.isSafeInteger(size) || size < 1 || size > 256) throw new RangeError('Synthetic size must be 1..256');
  const types = Array.from({length: size}, (_, index) => `  <xs:complexType name="T${index}"><xs:sequence><xs:group ref="t:Pair"/><xs:element name="next" type="t:T${index}" minOccurs="0"/></xs:sequence></xs:complexType>`);
  return ['<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema" xmlns:t="urn:preparation:synthetic" targetNamespace="urn:preparation:synthetic" elementFormDefault="qualified">',
    '  <xs:group name="Pair"><xs:sequence><xs:element name="a" type="xs:string"/><xs:element name="b" type="xs:int"/></xs:sequence></xs:group>',
    ...types, '  <xs:element name="root" type="t:T0"/>', '</xs:schema>', ''].join('\n');
}

export async function materializeSynthetic(root: string, size: number): Promise<PreparationCorpus> {
  const source = `tmp/conformance/preparation/corpus/shared-${size}.xsd`, bytes = syntheticSchema(size);
  await mkdir(path.dirname(path.resolve(root, source)), {recursive: true});
  await writeFile(path.resolve(root, source), bytes);
  return {id: `synthetic-${size}`, tier: 'synthetic', source, files: [{path: source, bytes: Buffer.byteLength(bytes), sha256: digest(bytes)}], basis: `Generated by syntheticSchema(${size}); ${size} independently recursive types share one two-element group; no production-service claim.`};
}
