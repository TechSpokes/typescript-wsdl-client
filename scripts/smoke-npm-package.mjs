import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {spawnSync} from "node:child_process";
import assert from "node:assert/strict";

const root = fileURLToPath(new URL("../", import.meta.url));
const artifacts = path.join(root, "tmp/preflight/package");
const cache = path.join(root, "tmp/cache/npm");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const lock = JSON.parse(fs.readFileSync(path.join(root, "package-lock.json"), "utf8"));
fs.mkdirSync(artifacts, {recursive: true});
const consumer = fs.mkdtempSync(path.join(os.tmpdir(), "wsdl-package-consumer-"));
const env = {...process.env, npm_config_cache: cache, NODE_OPTIONS: "--use-system-ca"};
delete env.NODE_PATH;
const log = [];
const npmCli = process.env.npm_execpath;
if (!npmCli) throw new Error("Run this check using npm run package:smoke");

function run(args, cwd = consumer, expected = 0) {
  const result = spawnSync(process.execPath, args, {cwd, env, encoding: "utf8", timeout: 180_000, maxBuffer: 16 * 1024 * 1024});
  log.push(JSON.stringify({args, cwd, status: result.status, stdout: result.stdout, stderr: result.stderr, error: result.error?.message}));
  assert.equal(result.status, expected, `${args.join(" ")}\n${result.error ?? ""}\n${result.stdout}\n${result.stderr}`);
  return result;
}
function npm(args, cwd = consumer) {
  return run([npmCli, ...args, "--ignore-scripts", "--no-audit", "--no-fund"], cwd);
}
function write(file, content) {
  const target = path.join(consumer, file);
  fs.mkdirSync(path.dirname(target), {recursive: true});
  fs.writeFileSync(target, content);
}
function json(file, value) { write(file, JSON.stringify(value, null, 2) + "\n"); }
function exact(name) {
  const version = lock.packages[`node_modules/${name}`]?.version;
  assert.ok(version, `Missing locked version: ${name}`);
  return `${name}@${version}`;
}
function headers(directory, scaffold = false) {
  const paths = fs.readdirSync(path.join(consumer, directory), {recursive: true, withFileTypes: true})
    .filter(entry => entry.isFile() && entry.name.endsWith(".ts"))
    .map(entry => path.join(entry.parentPath, entry.name)).sort();
  assert.ok(paths.length, `No TypeScript in ${directory}`);
  for (const file of paths) {
    const text = fs.readFileSync(file, "utf8");
    assert.ok(text.startsWith("/* eslint-disable */\n"), file);
    assert.equal(text.split("/* eslint-disable */").length, 2, file);
    assert.ok(text.includes(scaffold ? "// Scaffold generated by" : "// Generated by"), file);
  }
  return paths.length;
}

try {
  const packed = JSON.parse(npm(["pack", "--json", "--pack-destination", artifacts], root).stdout);
  const pack = Array.isArray(packed) ? packed[0] : Object.values(packed)[0];
  assert.ok(pack.filename && path.basename(pack.filename) === pack.filename);
  json("package.json", {name: "preamble-package-consumer", private: true, type: "module"});
  npm(["install", "--omit=dev", path.join(artifacts, pack.filename)]);
  const installed = path.join(consumer, "node_modules/@techspokes/typescript-wsdl-client");
  const cli = path.join(installed, "dist/cli.js");
  const command = args => run([cli, ...args]);
  fs.copyFileSync(path.join(root, "examples/minimal/weather.wsdl"), path.join(consumer, "weather.wsdl"));
  run(["--input-type=module", "-e", "import {createRequire} from 'node:module'; const require=createRequire(import.meta.url); try {require.resolve('typescript'); process.exit(2);} catch(e) {if(e.code !== 'MODULE_NOT_FOUND') throw e;}"]);
  const pipeline = ["pipeline", "--wsdl-source", "weather.wsdl", "--client-dir", ".generated/client", "--openapi-file", ".generated/openapi.json", "--gateway-dir", ".generated/gateway", "--gateway-service-name", "weather", "--gateway-version-prefix", "v1", "--openapi-format", "json", "--init-app", "--test-dir", ".generated/tests"];
  command(pipeline);
  command(["client", "--wsdl-source", "weather.wsdl", "--client-dir", "from-wsdl"]);
  command(["client", "--catalog-file", ".generated/client/catalog.json", "--client-dir", "from-catalog"]);
  command(["gateway", "--openapi-file", ".generated/openapi.json", "--client-dir", ".generated/client", "--gateway-dir", ".generated/standalone", "--gateway-service-name", "weather", "--gateway-version-prefix", "v1"]);
  command(["app", "--client-dir", ".generated/client", "--gateway-dir", ".generated/gateway", "--openapi-file", ".generated/openapi.json", "--app-dir", ".generated/standalone-app"]);
  json("stream.json", {operations: {GetWeatherInformation: {format: "json-array", recordType: "WeatherDescription", recordPath: ["GetWeatherInformationResponse", "GetWeatherInformationResult", "WeatherDescription"]}}});
  command(["client", "--wsdl-source", "weather.wsdl", "--client-dir", "stream-client", "--stream-config", "stream.json"]);
  assert.ok(fs.existsSync(path.join(consumer, "stream-client/streamXml.ts")));
  write("api.mjs", [
    'import {compileWsdlToProject, generateGateway, generateTests, runGenerationPipeline} from "@techspokes/typescript-wsdl-client";',
    'await compileWsdlToProject({wsdl: "weather.wsdl", outDir: "api-client", options: {imports: "js"}});',
    'await generateGateway({openapiFile: ".generated/openapi.json", clientDir: ".generated/client", outDir: ".generated/api-gateway", serviceSlug: "weather", versionSlug: "v1"});',
    'await generateTests({clientDir: ".generated/client", gatewayDir: ".generated/gateway", catalogFile: ".generated/client/catalog.json", testDir: ".generated/api-tests"});',
    'await runGenerationPipeline({wsdl: "weather.wsdl", catalogOut: "api-pipeline/catalog.json", clientOutDir: "api-pipeline"});',
  ].join("\n"));
  run(["api.mjs"]);
  let count = 0;
  for (const directory of [".generated/client", ".generated/gateway", ".generated/standalone", ".generated/api-gateway", "from-wsdl", "from-catalog", "stream-client", "api-client", "api-pipeline"]) count += headers(directory);
  for (const directory of [".generated/app", ".generated/standalone-app", ".generated/tests", ".generated/api-tests"]) count += headers(directory, true);
  const appPackage = JSON.parse(fs.readFileSync(path.join(consumer, ".generated/app/package.json"), "utf8"));
  npm(["install", ...Object.keys(appPackage.dependencies).map(exact)]);
  npm(["install", "--save-dev", ...["typescript", "@types/node", "vitest"].map(exact)]);
  run(["node_modules/typescript/bin/tsc", "--noEmit", "-p", ".generated/app/tsconfig.json"]);
  run([path.join(consumer, "node_modules/vitest/vitest.mjs"), "run", "--config", "vitest.config.ts"], path.join(consumer, ".generated/tests"));

  const preamble = path.join(installed, "src/generation/preambles/typescript.preamble");
  fs.renameSync(preamble, preamble + ".removed");
  const failed = run([cli, "client", "--wsdl-source", "weather.wsdl", "--client-dir", "broken-client"], consumer, 1);
  assert.match(failed.stderr, /preamble/);
  assert.ok(!fs.existsSync(path.join(consumer, "broken-client/client.ts")));
  write("broken-api.mjs", 'import {compileWsdlToProject} from "@techspokes/typescript-wsdl-client"; await compileWsdlToProject({wsdl:"weather.wsdl",outDir:"broken-api"});');
  assert.match(run(["broken-api.mjs"], consumer, 1).stderr, /preamble/);
  console.log(`Installed package ${manifest.version} smoke passed: ${count} TypeScript artifacts, CLI/API generation, consumer typecheck/tests, missing-resource failures.`);
} finally {
  fs.writeFileSync(path.join(artifacts, "consumer-smoke.log"), log.join("\n") + "\n");
  const resolved = path.resolve(consumer);
  if (path.dirname(resolved) !== path.resolve(os.tmpdir()) || !path.basename(resolved).startsWith("wsdl-package-consumer-")) {
    throw new Error(`Refusing cleanup outside the created consumer directory: ${resolved}`);
  }
  fs.rmSync(resolved, {recursive: true, force: true});
}
